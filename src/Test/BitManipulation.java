package Test;

public class BitManipulation {

    public static void main(String[] args) {
        int x = 5 ;
        System.out.println(x << 1); // 5 * (2*1)
        System.out.println(x *(2*1));

        System.out.println(x << 3); // 5 * (2*1)
        System.out.println(x *(2*2*2));

        System.out.println(x << 2); // 5 * (2*1)
        System.out.println(x *(2*2));

        System.out.println(10<<3); // 10 * 8 = 80

        System.out.println(40 >> 2); // 40 /4 = 10
        System.out.println(-16 >>> 2); // 40 /4 = 10





    }
}
